#!/usr/bin/env python3
"""Generate the Vulkan side of the KI upscaler from an mpv FSRCNNX-style shader:

  * one GLSL 450 compute shader per network pass (8x8 workgroups, input-resolution grid)
  * ki_window.frag: draws the game window at screen size from the 2x luma sub-pixels
  * ki_spirv.h: all of the above compiled to SPIR-V (uint32 arrays) + pass metadata

Image coordinates are y-down in Vulkan, the same as mpv, so offsets are used as-is.

Usage: gen_vulkan.py <net.glsl> <glslang binary> <out_dir>
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import convert_mpv_shader as conv  # noqa: E402

MAX_BINDS = 3

COMPUTE_TEMPLATE = """#version 450
layout(local_size_x = 8, local_size_y = 8) in;
layout(push_constant) uniform PC { ivec2 inputSize; } pc;
layout(binding = 3, rgba16f) uniform writeonly image2D outImg;
ivec2 kiCoord(vec2 off) {
    ivec2 p = ivec2(gl_GlobalInvocationID.xy) + ivec2(off);
    return clamp(p, ivec2(0), pc.inputSize - 1);
}
%(decls)s
%(body)s
void main() {
    if (any(greaterThanEqual(ivec2(gl_GlobalInvocationID.xy), pc.inputSize))) return;
    imageStore(outImg, ivec2(gl_GlobalInvocationID.xy), hookPass());
}
"""

WINDOW_FRAG = """#version 450
// KI upscaler output for the game window (Vulkan renderer). Same push constants as window.frag.
layout(set = 0, binding = 0) uniform sampler2D texSampler;   // game window, linear sampler
layout(set = 1, binding = 0) uniform sampler2D subPixels;    // network output, 4 sub-pixels / texel
layout(push_constant) uniform PC {
    float ndcX0; float ndcY0; float ndcX1; float ndcY1;
    int useTexAlpha; int effectId; float sharpness; float resW; float resH;
    int effectMask; float brightness; float contrast; float gamma; float outW; float outH;
} pc;
layout(location = 0) in vec2 fragTexCoord;
layout(location = 0) out vec4 outColor;
const vec3 LUMA_W = vec3(0.2126, 0.7152, 0.0722);

float hiLuma(ivec2 q, ivec2 inSize) {
    q = clamp(q, ivec2(0), inSize * 2 - 1);
    ivec2 texel = q / 2;
    ivec2 sub = q - texel * 2;
    int idx = sub.x * 2 + sub.y;          // mpv: res[index.x * 2 + index.y], y down
    vec4 s = texelFetch(subPixels, texel, 0);
    return idx == 0 ? s.x : (idx == 1 ? s.y : (idx == 2 ? s.z : s.w));
}

vec3 colorAdjust(vec3 c) {
    c = c + pc.brightness;
    c = (c - 0.5) * (1.0 + pc.contrast) + 0.5;
    c = pow(clamp(c, 0.0, 1.0), vec3(1.0 / max(pc.gamma, 0.01)));
    return c;
}

void main() {
    vec2 uv = fragTexCoord;
    vec3 base = texture(texSampler, uv).rgb;
    ivec2 inSize = ivec2(max(vec2(pc.resW, pc.resH), vec2(1.0)));
    vec2 p = uv * vec2(inSize) * 2.0 - 0.5;
    vec2 i0 = floor(p);
    vec2 f = p - i0;
    ivec2 q = ivec2(i0);
    float y00 = hiLuma(q, inSize);
    float y10 = hiLuma(q + ivec2(1, 0), inSize);
    float y01 = hiLuma(q + ivec2(0, 1), inSize);
    float y11 = hiLuma(q + ivec2(1, 1), inSize);
    float yHi = mix(mix(y00, y10, f.x), mix(y01, y11, f.x), f.y);
    // sharpness (0..1) carries the detail strength / 1.5 (so 0.667 = network as trained)
    vec3 rgb = clamp(base + (yHi - dot(base, LUMA_W)) * (pc.sharpness * 1.5), 0.0, 1.0);
    outColor = vec4(colorAdjust(rgb), 1.0);
}
"""


def compute_source(binds, body):
    decls = []
    for i, b in enumerate(binds):
        decls.append("layout(binding = %d) uniform sampler2D %s;" % (i, b))
        if b == "LUMA":
            decls.append("vec4 LUMA_texOff(vec2 off) { return vec4(dot(texelFetch(LUMA, kiCoord(off), 0).rgb, "
                         "vec3(0.2126, 0.7152, 0.0722))); }")
        else:
            decls.append("vec4 %s_texOff(vec2 off) { return texelFetch(%s, kiCoord(off), 0); }" % (b, b))
    return COMPUTE_TEMPLATE % {"decls": "\n".join(decls), "body": body}


def spirv_words(glslang, path, stage):
    out = path + ".spv"
    subprocess.run([glslang, "-V", "-S", stage, "-o", out, path], check=True, stdout=subprocess.PIPE)
    data = open(out, "rb").read()
    return [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]


def c_array(name, words):
    lines = ["static const uint32_t %s[] = {" % name]
    for i in range(0, len(words), 8):
        lines.append("    " + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    net_path, glslang, out_dir = sys.argv[1:4]
    os.makedirs(out_dir, exist_ok=True)
    src = open(net_path, encoding="utf-8").read()
    passes = [p for p in conv.parse(src) if p["save"] is not None]
    names = []
    for p in passes:
        for b in p["binds"]:
            if b != "LUMA" and b not in names:
                names.append(b)
        if p["save"] not in names:
            names.append(p["save"])
    hdr = ["// GENERATED by ki/tools/gen_vulkan.py from %s. Do not edit." % os.path.basename(net_path),
           "#pragma once", "#include <cstdint>", "#include <cstddef>", ""]
    pass_rows = []
    for i, p in enumerate(passes):
        if len(p["binds"]) > MAX_BINDS:
            raise SystemExit("pass %d binds too many textures" % i)
        glsl = compute_source(p["binds"], conv.translate_body(p["body"]))
        path = os.path.join(out_dir, "ki_pass_%02d.comp" % i)
        open(path, "w").write(glsl)
        words = spirv_words(glslang, path, "comp")
        hdr.append(c_array("ki_pass_%02d_spv" % i, words))
        bind_idx = [(-1 if b == "LUMA" else names.index(b)) for b in p["binds"]]
        bind_idx += [-2] * (MAX_BINDS - len(bind_idx))
        pass_rows.append("    { ki_pass_%02d_spv, sizeof(ki_pass_%02d_spv), %d, { %s }, %d },  // %s" % (
            i, i, len(p["binds"]), ", ".join(str(b) for b in bind_idx), names.index(p["save"]), p["desc"]))
    fpath = os.path.join(out_dir, "ki_window.frag")
    open(fpath, "w").write(WINDOW_FRAG)
    hdr.append(c_array("ki_window_frag_spv", spirv_words(glslang, fpath, "frag")))
    hdr += ["",
            "struct KiPassInfo {",
            "    const uint32_t* code; size_t size;",
            "    int bindCount;",
            "    int binds[%d];   // -1 = game window (LUMA), -2 = unused, else index into intermediate images" % MAX_BINDS,
            "    int save;       // index into intermediate images",
            "};",
            "static constexpr int KI_IMAGE_COUNT = %d;   // %s" % (len(names), ", ".join(names)),
            "static constexpr int KI_PASS_COUNT = %d;" % len(passes),
            "static constexpr int KI_OUTPUT_IMAGE = %d;  // %s" % (names.index(passes[-1]["save"]), passes[-1]["save"]),
            "static const KiPassInfo KI_PASSES[KI_PASS_COUNT] = {"] + pass_rows + ["};", ""]
    open(os.path.join(out_dir, "ki_spirv.h"), "w").write("\n".join(hdr))
    print("generated %d compute passes, %d images -> %s" % (len(passes), len(names), out_dir))


if __name__ == "__main__":
    main()
