#!/usr/bin/env python3
"""Convert an mpv user shader (FSRCNNX-style, LUMA hooks) into a Java class
that GameNative's KiUpscaleEffect can run on GLES 3.

Only the subset FSRCNNX uses is supported: //!HOOK LUMA, //!BIND, //!SAVE,
//!COMPONENTS 4, NAME_texOff(...), and a final "aggregation" pass that
rearranges 4 sub-pixels per texel into a 2x image. The aggregation pass is not
emitted; KiUpscaleEffect does that step itself in its output shader.

Usage: convert_mpv_shader.py <input.glsl> <output.java> <ClassName>
"""
import re
import sys


def parse(src):
    blocks = re.split(r"(?m)^(?=//!HOOK)", src)
    passes = []
    for block in blocks:
        if not block.startswith("//!HOOK"):
            continue
        meta = {"binds": [], "save": None, "desc": "", "width": None}
        body_lines = []
        for line in block.splitlines():
            m = re.match(r"//!(\w+)\s*(.*)", line)
            if m:
                key, val = m.group(1), m.group(2).strip()
                if key == "BIND":
                    meta["binds"].append(val)
                elif key == "SAVE":
                    meta["save"] = val
                elif key == "DESC":
                    meta["desc"] = val
                elif key == "WIDTH":
                    meta["width"] = val
                elif key == "COMPONENTS" and val != "4":
                    raise SystemExit("unsupported COMPONENTS %s" % val)
            else:
                body_lines.append(line)
        meta["body"] = "\n".join(body_lines).strip()
        passes.append(meta)
    return passes


def translate_body(body):
    body = body.replace("mat4x4(", "mat4(")
    # texOff(0) with an int literal has no vec2 overload in GLSL ES 3.
    body = re.sub(r"(\w+)_texOff\(\s*0\s*\)", r"\1_texOff(vec2(0.0))", body)
    # vec2(-1,0) style integer literals are fine for vec2 constructors.
    body = body.replace("vec4 hook()", "vec4 hookPass()")
    return body


def java_string(text):
    out = []
    for line in text.splitlines():
        line = line.replace("\\", "\\\\").replace('"', '\\"')
        out.append('            "' + line + '\\n"')
    return " +\n".join(out) if out else '""'


def main():
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    src_path, out_path, class_name = sys.argv[1:]
    src = open(src_path, encoding="utf-8").read()
    header = src.split("//!HOOK", 1)[0].strip()
    passes = parse(src)

    network = [p for p in passes if p["save"] is not None]
    final = [p for p in passes if p["save"] is None]
    if len(final) != 1 or "aggregation" not in final[0]["desc"]:
        raise SystemExit("expected exactly one final aggregation pass")
    last_save = network[-1]["save"]

    lines = []
    lines.append("package com.winlator.renderer.effects.ki;")
    lines.append("")
    lines.append("/**")
    lines.append(" * GENERATED by ki/tools/convert_mpv_shader.py from an mpv user shader. Do not edit.")
    lines.append(" *")
    lines.append(" * Original shader header:")
    for h in header.splitlines():
        lines.append(" * " + h.lstrip("/ ").rstrip())
    lines.append(" */")
    lines.append("public final class %s implements KiNetwork {" % class_name)
    lines.append("    private static final String[] NAMES = {")
    for p in network:
        lines.append('        "%s",' % p["desc"])
    lines.append("    };")
    lines.append("    private static final String[][] BINDS = {")
    for p in network:
        lines.append("        {" + ", ".join('"%s"' % b for b in p["binds"]) + "},")
    lines.append("    };")
    lines.append("    private static final String[] SAVES = {")
    for p in network:
        lines.append('        "%s",' % p["save"])
    lines.append("    };")
    lines.append("    private static final String[] BODIES = {")
    for p in network:
        lines.append(java_string(translate_body(p["body"])) + ",")
    lines.append("    };")
    lines.append("")
    lines.append("    @Override public int passCount() { return NAMES.length; }")
    lines.append("    @Override public String passName(int i) { return NAMES[i]; }")
    lines.append("    @Override public String[] passBinds(int i) { return BINDS[i]; }")
    lines.append("    @Override public String passSave(int i) { return SAVES[i]; }")
    lines.append("    @Override public String passBody(int i) { return BODIES[i]; }")
    lines.append('    @Override public String outputTexture() { return "%s"; }' % last_save)
    lines.append("}")
    lines.append("")
    open(out_path, "w", encoding="utf-8").write("\n".join(lines))
    print("wrote %s: %d network passes, output %s" % (out_path, len(network), last_save))


if __name__ == "__main__":
    main()
